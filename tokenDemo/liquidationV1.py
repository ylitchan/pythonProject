w3 = Web3(Web3.HTTPProvider(NODE_URL))
w3.eth.account.enable_unaudited_hdwallet_features()
chainId = w3.eth.chain_id
with open('PRIVATE_MNEMONIC', 'r') as f:
    PRIVATE_MNEMONIC = f.read()
ACCOUNT = w3.eth.account.from_mnemonic(PRIVATE_MNEMONIC)  # .from_key(PRIVATE_KEY)
WALLET_ADDRESS = ACCOUNT.address
contract_lybra = w3.eth.contract(address=Web3.to_checksum_address(LYBRA_CONTRACT_ADDRESS), abi=LYBRA_ABI)
contract_eusd = w3.eth.contract(address=Web3.to_checksum_address(EUSD_CONTRACT_ADDRESS), abi=EUSD_ABI)
badCollateralRatio = 150000000000000000000
session = requests.Session()
session.headers = {'Content-Type': 'application/json'}


def send_msg(msg):
    try:
        print(msg)
        json_msg = {
            "msgtype": "text",
            "text": {'content': msg}
        }
        session.post(
            url='https://qyapi.weixin.qq.com/cgi-bin/webhook/send?key=6f2ec864-c474-4c8f-b069-1e3c35eb7d73',
            json=json_msg)
    except:
        return


def get_close():
    current_time = int(datetime.now().timestamp())
    response = requests.get("https://prices.curve.finance/v1/ohlc/ethereum/0x2673099769201c08E9A5e63b25FBaF25541A6557",
                            params={
                                'main_token': "0xA0b86991c6218b36c1d19D4a2e9Eb0cE3606eB48",
                                'reference_token': "0xdf3ac4F479375802A821f7b7b46Cd7EB5E4262cC",
                                'agg_number': "15",
                                'agg_units': "minute",
                                'start': current_time - 15 * 60,
                                'end': current_time
                            })
    return response.json()['data'][-1]['close']


async def provider():
    print(datetime.now(), '开始扫描')
    target_address_set = set()

    async def onBehalfOfAddress(target_address):
        try:
            borrowed = await asyncio.to_thread(contract_eusd.functions.getBorrowedOf(target_address).call)
            if not borrowed:
                return
            depositedAsset = await asyncio.to_thread(contract_eusd.functions.depositedEther(target_address).call)
            assetValue = depositedAsset * assetPrice
            onBehalfOfCollateralRatio = (assetValue * 100) / borrowed
            print(target_address, onBehalfOfCollateralRatio / 10e19, assetValue / 10e35)
            if onBehalfOfCollateralRatio >= badCollateralRatio:
                return
            target_address_set.add((target_address, onBehalfOfCollateralRatio, depositedAsset))
            send_msg(f'V1清算地址:{target_address}\n抵押率:{onBehalfOfCollateralRatio}\n资产:{depositedAsset}')

        except:
            return

    def keeper(arg):
        try:
            # 查询余额
            eusdAmount = contract_eusd.functions.balanceOf(WALLET_ADDRESS).call()
            if eusdAmount < 50:
                return
            target_address, onBehalfOfCollateralRatio, depositedAsset = arg
            if superLiquidation and onBehalfOfCollateralRatio < 125 * 1e18:
                assetAmount = int(min(eusdAmount * 1e18 / assetPrice, depositedAsset))
            else:
                assetAmount = int(min(eusdAmount * 1e18 / assetPrice, depositedAsset / 2))
            if assetAmount * assetPrice * 0.1 / 10e27 <= w3.eth.gas_price * 1.3 * 4:
                return
            if superLiquidation:
                tx = contract_eusd.functions.superLiquidation(
                    WALLET_ADDRESS, target_address, assetAmount
                )
            else:
                tx = contract_eusd.functions.liquidation(
                    WALLET_ADDRESS, target_address, assetAmount
                )
            gas_price = int((w3.eth.get_block('latest')[
                                 'baseFeePerGas'] + w3.eth.max_priority_fee * 10e2) * 1.3)
            tx = tx.build_transaction({
                'chainId': chainId,  # 主网
                'maxFeePerGas': gas_price,
                'maxPriorityFeePerGas': gas_price,
                'gas': 2000000,
                'nonce': w3.eth.get_transaction_count(ACCOUNT.address),
            })
            # 签名交易
            signed_tx = ACCOUNT.sign_transaction(tx)
            # 发送交易
            tx_hash = w3.eth.send_raw_transaction(signed_tx.rawTransaction)
            print(f"V1交易哈希: {tx_hash.hex()}")
            send_msg(f"V1清算哈希: {tx_hash.hex()}")
            if tx_hash:
                # 等待确认
                receipt = w3.eth.wait_for_transaction_receipt(tx_hash)
                print(f"Approve confirmed in block {receipt['blockNumber']}")
        except:
            traceback.print_exc()

    # address_borrowed = ['0x7E6601A0Cb2B5aE129c09661846a053ea07223Fb']
    while 1:
        try:
            assetPrice = contract_lybra.functions.getAssetPrice().call()
            overallCollateralRatio = (132555446020770040044 * assetPrice * 100) / 175268560142824841438498
            if overallCollateralRatio < badCollateralRatio:
                superLiquidation = True
            else:
                superLiquidation = False
            break
        except:
            await asyncio.sleep(300)
            continue
    await asyncio.gather(*[onBehalfOfAddress(target_address) for target_address in address_borrowed])
    if get_close() > 1.09:
        return
    target_address_set = sorted(target_address_set, key=lambda x: x[-1], reverse=True)
    for a in target_address_set:
        keeper(a)


async def main():
    await provider()
    # 设置任务调度
    scheduler.add_job(provider, 'cron', hour='*', minute='*/59', second='00', timezone='Asia/Shanghai')
    # 启动调度器
    scheduler.start()
    stop_event = asyncio.Event()
    await stop_event.wait()  # 等待事件触发


if __name__ == "__main__":
    scheduler = AsyncIOScheduler()
    asyncio.run(main())
